import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { format } from "prettier";
import { rolldown } from "rolldown";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));

export const assetsPath = resolve(root, "lib/widget/generated/assets.ts");

async function bundle(entry) {
  const build = await rolldown({
    input: resolve(root, entry),
    tsconfig: false,
    transform: { target: "es2022" },
  });
  const { output } = await build.generate({ format: "iife", minify: true });
  await build.close();
  if (output.length !== 1) throw new Error(`${entry} must be one file.`);
  const code = output[0].code.trim();
  // The frame script is inlined into a document.
  if (/<\/script|<!--/i.test(code)) {
    throw new Error(`${entry} cannot be inlined.`);
  }
  return code;
}

const minifyCss = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/ ?([{};,]) ?/g, "$1")
    .trim();

const cspHash = (text) =>
  `sha256-${createHash("sha256").update(text, "utf8").digest("base64")}`;

/** Source of the generated module. Same input and versions, same output. */
export async function generateWidgetAssets() {
  const loader = await bundle("widget/loader.ts");
  const frame = await bundle("widget/frame.ts");
  const style = minifyCss(
    readFileSync(resolve(root, "widget/frame.css"), "utf8"),
  );
  const values = {
    loaderScript: loader,
    loaderEtag: `"${createHash("sha256").update(loader).digest("hex").slice(0, 32)}"`,
    frameScript: frame,
    frameScriptHash: cspHash(frame),
    frameStyle: style,
    frameStyleHash: cspHash(style),
  };
  const source = [
    "// Generated by `npm run widget:build` from widget/. Do not edit.",
    ...Object.entries(values).map(
      ([name, value]) => `export const ${name} = ${JSON.stringify(value)};`,
    ),
  ].join("\n");
  return format(source, { parser: "typescript" });
}
